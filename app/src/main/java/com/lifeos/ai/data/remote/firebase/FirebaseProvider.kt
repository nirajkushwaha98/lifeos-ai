package com.lifeos.ai.data.remote.firebase

import android.content.Context
import android.util.Log
import com.google.firebase.FirebaseApp
import com.google.firebase.analytics.FirebaseAnalytics
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.crashlytics.FirebaseCrashlytics
import com.google.firebase.firestore.FirebaseFirestore
import com.google.firebase.functions.FirebaseFunctions
import dagger.hilt.android.qualifiers.ApplicationContext
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Single access point for Firebase SDKs. When `app/google-services.json` is missing the default
 * FirebaseApp is never initialized; every accessor then returns null and the app keeps working
 * in local-only mode instead of crashing.
 */
@Singleton
class FirebaseProvider @Inject constructor(@ApplicationContext private val context: Context) {

    val isConfigured: Boolean by lazy {
        runCatching { FirebaseApp.getApps(context).isNotEmpty() }.getOrDefault(false)
    }

    val auth: FirebaseAuth? get() = if (isConfigured) FirebaseAuth.getInstance() else null
    val firestore: FirebaseFirestore? get() = if (isConfigured) FirebaseFirestore.getInstance() else null
    /** Must match the region in backend/functions/index.js. */
    val functions: FirebaseFunctions? get() = if (isConfigured) FirebaseFunctions.getInstance(FUNCTIONS_REGION) else null

    fun applyPrivacySettings(analyticsEnabled: Boolean, crashReportsEnabled: Boolean) {
        if (!isConfigured) return
        runCatching {
            FirebaseAnalytics.getInstance(context).setAnalyticsCollectionEnabled(analyticsEnabled)
            FirebaseCrashlytics.getInstance().isCrashlyticsCollectionEnabled = crashReportsEnabled
        }.onFailure { Log.w(TAG, "Unable to apply privacy settings", it) }
    }

    fun logEvent(name: String, params: Map<String, String> = emptyMap()) {
        if (!isConfigured) return
        runCatching {
            val bundle = android.os.Bundle().apply { params.forEach { (k, v) -> putString(k, v) } }
            FirebaseAnalytics.getInstance(context).logEvent(name, bundle)
        }
    }

    fun recordNonFatal(t: Throwable) {
        Log.e(TAG, "Non-fatal", t)
        if (!isConfigured) return
        runCatching { FirebaseCrashlytics.getInstance().recordException(t) }
    }

    /** Web client id generated by the google-services plugin when Google sign-in is enabled. */
    fun googleWebClientId(): String? {
        @Suppress("DiscouragedApi")
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id != 0) context.getString(id).takeIf { it.isNotBlank() } else null
    }

    companion object {
        private const val TAG = "FirebaseProvider"
        const val FUNCTIONS_REGION = "asia-south1"
    }
}
